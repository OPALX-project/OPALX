# -----------------------------------------------------------------------------
# Category mapping
# -----------------------------------------------------------------------------

def category_of(element):
    """Return the visualization category for an element description."""
    etype = element['type']
    if etype == 'SOLENOID':
        return 'Solenoids'
    if etype == 'DRIFT':
        return 'Drifts'
    if etype == 'MONITOR':
        return 'Monitors'
    if etype in ('MULTIPOLE', 'MULTIPOLET'):
        if element.get('multipole_order') == 2:
            return 'Quadrupoles'
        return 'Multipoles'
    if etype in ('SBEND', 'RBEND', 'RBEND3D'):
        return 'Bends'
    if etype == 'COLLIMATOR':
        return 'Collimators'
    if etype in ('RFCAVITY', 'TRAVELINGWAVE', 'CONSTANTEFIELDCAVITY'):
        return 'Cavities'
    return 'Other'


# -----------------------------------------------------------------------------
# Pose / placement helpers
# -----------------------------------------------------------------------------

def pose_matrix(element):
    """4x4 homogeneous matrix mapping element-local to global coordinates."""
    T = np.eye(4)
    T[:3, :3] = np.asarray(element['rotation'], dtype=float)
    T[:3, 3] = np.asarray(element['position'], dtype=float)
    return T


def place(mesh, element):
    """Transform mesh from element-local to global coordinates in-place."""
    mesh.transform(pose_matrix(element), inplace=True)
    return mesh


# -----------------------------------------------------------------------------
# Aperture clamping
# -----------------------------------------------------------------------------

def effective_transverse(element, args, reference):
    """Return ((semi_x, semi_y), clamped) applying the clamp policy."""
    transverse = element.get('transverse')
    absurd = (
        transverse is None
        or transverse['semi_x'] > args.clamp_threshold
        or transverse['semi_y'] > args.clamp_threshold
    )
    if not absurd:
        return (transverse['semi_x'], transverse['semi_y']), False
    if args.no_clamp and transverse is not None:
        return (transverse['semi_x'], transverse['semi_y']), False
    if args.clamp_radius is not None:
        radius = args.clamp_radius
    elif reference is not None:
        radius = 0.5 * (reference[0] + reference[1])
    else:
        radius = 0.1
    return (radius, radius), True


# -----------------------------------------------------------------------------
# Cross-section definitions
# -----------------------------------------------------------------------------

def elliptical_loop(semi_x, semi_y, n=32):
    """Return an elliptical cross-section loop in (u, v) coordinates.

    u is the radial/horizontal direction, v is the vertical direction.
    Vertices are ordered counter-clockwise when looking along -z (i.e. from the
    end of the element back toward its start), which gives outward-pointing
    side normals after sweeping along a path.
    """
    theta = np.linspace(0.0, 2.0 * math.pi, n, endpoint=False)
    return np.column_stack([semi_x * np.cos(theta), semi_y * np.sin(theta)])


def rectangular_loop(semi_x, semi_y):
    """Return a rectangular cross-section loop in (u, v) coordinates."""
    return np.array([
        [semi_x, semi_y],
        [-semi_x, semi_y],
        [-semi_x, -semi_y],
        [semi_x, -semi_y],
    ])


def hollow_elliptical_loop(outer_semi_x, outer_semi_y, inner_scale=0.45, n=32):
    """Return outer and inner elliptical loops for a hollow tube.

    The inner loop is reversed so that its winding is opposite to the outer
    loop, which keeps the side-surface normals consistent.
    """
    outer = elliptical_loop(outer_semi_x, outer_semi_y, n)
    inner = elliptical_loop(
        inner_scale * outer_semi_x, inner_scale * outer_semi_y, n
    )[::-1]
    return [outer, inner]


# -----------------------------------------------------------------------------
# Generic sweep along a path
# -----------------------------------------------------------------------------

def _compute_path_frames(path):
    """Compute (tangent, normal, binormal) frames along a path.

    The path is assumed to be a planar bend in the x-z plane or a straight line
    along z. normal lies in the bend plane (radial direction), binormal is
    vertical (y).
    """
    path = np.asarray(path, dtype=float)
    n = len(path)
    tangents = np.empty((n, 3))
    for i in range(n):
        if i == 0:
            delta = path[1] - path[0]
        elif i == n - 1:
            delta = path[-1] - path[-2]
        else:
            delta = path[i + 1] - path[i - 1]
        norm = np.linalg.norm(delta)
        if norm > 0.0:
            tangents[i] = delta / norm
        else:
            tangents[i] = np.array([0.0, 0.0, 1.0])

    normals = np.empty((n, 3))
    binormals = np.empty((n, 3))
    up = np.array([0.0, 1.0, 0.0])
    for i in range(n):
        t = tangents[i]
        ref = up
        if abs(np.dot(t, up)) > 0.99:
            ref = np.array([1.0, 0.0, 0.0])
        nvec = np.cross(ref, t)
        nnorm = np.linalg.norm(nvec)
        if nnorm < 1e-12:
            nvec = np.cross(np.array([0.0, 0.0, 1.0]), t)
            nnorm = np.linalg.norm(nvec)
        nvec /= nnorm
        bvec = np.cross(t, nvec)
        bnorm = np.linalg.norm(bvec)
        if bnorm > 0.0:
            bvec /= bnorm
        normals[i] = nvec
        binormals[i] = bvec

    return tangents, normals, binormals


def sweep_profile(path, loops, caps=True):
    """Sweep one or more closed loops along a 3D path.

    Parameters
    ----------
    path : (N, 3) array-like
        Path points in local coordinates.
    loops : list of (M, 2) array-like
        Cross-section loops given as (u, v) coordinates. u maps to the local
        normal/radial direction, v to the local vertical direction.
    caps : bool
        If True and a single loop is supplied, close the start and end with
        triangulated caps. Multi-loop (hollow) profiles are left open.

    Returns
    -------
    pv.PolyData or None
    """
    path = np.asarray(path, dtype=float)
    if len(path) < 2:
        return None

    loops = [np.asarray(loop, dtype=float) for loop in loops]
    if not loops or any(len(loop) < 3 for loop in loops):
        return None

    _, normals, binormals = _compute_path_frames(path)
    n_points = len(path)
    vertices_per_cross = sum(len(loop) for loop in loops)

    # Build all 3D vertices: path[i] + u*normal[i] + v*binormal[i]
    vertices = np.empty((n_points * vertices_per_cross, 3))
    for i in range(n_points):
        base = i * vertices_per_cross
        offset = 0
        p = path[i]
        N = normals[i]
        B = binormals[i]
        for loop in loops:
            m = len(loop)
            segment = loop[:, 0, np.newaxis] * N + loop[:, 1, np.newaxis] * B
            vertices[base + offset : base + offset + m] = p + segment
            offset += m

    faces = []

    # Side walls between consecutive cross-sections
    for i in range(n_points - 1):
        base0 = i * vertices_per_cross
        base1 = (i + 1) * vertices_per_cross
        offset = 0
        for loop in loops:
            m = len(loop)
            for j in range(m):
                j0 = offset + j
                j1 = offset + (j + 1) % m
                v00 = base0 + j0
                v01 = base0 + j1
                v10 = base1 + j0
                v11 = base1 + j1
                faces.append([3, v00, v01, v11])
                faces.append([3, v00, v11, v10])
            offset += m

    # Caps (only for single-loop, solid profiles)
    if caps and len(loops) == 1:
        m = len(loops[0])

        # Start cap: reverse winding so outward normal points toward -z
        centroid_start = len(vertices)
        vertices = np.vstack([vertices, path[0].reshape(1, 3)])
        for j in range(m):
            faces.append(
                [3, centroid_start, (j + 1) % m, j]
            )

        # End cap: normal winding so outward normal points toward +z
        centroid_end = len(vertices)
        base_end = (n_points - 1) * vertices_per_cross
        vertices = np.vstack([vertices, path[-1].reshape(1, 3)])
        for j in range(m):
            faces.append(
                [3, centroid_end, base_end + j, base_end + (j + 1) % m]
            )

    if not faces:
        return None

    faces_arr = np.hstack(faces)
    return pv.PolyData(vertices, faces_arr)


# -----------------------------------------------------------------------------
# Low-level primitive helpers
# -----------------------------------------------------------------------------

def cylinder(length, semi_x, semi_y, capped=False, z0=0.0, scale=1.0):
    """Cylinder along local z from z0 to z0+length, elliptical via semi_x/semi_y."""
    height = max(length, 1e-9)
    mesh = pv.Cylinder(
        center=(0.0, 0.0, z0 + 0.5 * height),
        direction=(0.0, 0.0, 1.0),
        height=height,
        radius=max(scale * semi_x, 1e-9),
        resolution=36,
        capping=capped,
    )
    if semi_x > 0.0 and semi_y != semi_x:
        mesh.scale([1.0, semi_y / semi_x, 1.0], inplace=True)
    return mesh


def hollow_tube(length, semi_x, semi_y, inner_scale=0.45, z0=0.0, n=32):
    """Open hollow tube along local z, elliptical cross-section."""
    path = np.array([[0.0, 0.0, z0], [0.0, 0.0, z0 + length]])
    loops = hollow_elliptical_loop(semi_x, semi_y, inner_scale, n)
    return sweep_profile(path, loops, caps=False)


def box(length, semi_x, semi_y):
    return pv.Box(bounds=[-semi_x, semi_x, -semi_y, semi_y, 0.0, length])


def build_quadrupole(length, semi_x, semi_y):
    """Four pole pieces around the aperture.

    Pole thickness scales with the aperture but is clamped to a reasonable
    absolute range so that very large apertures (e.g. test decks with
    HAPERT/VAPERT = 2 m) still show four distinct poles instead of a solid
    cylinder.
    """
    pole_thick_x = min(max(0.45 * semi_x, 0.05), 0.3)
    pole_thick_y = min(max(0.45 * semi_y, 0.05), 0.3)
    pole_long_x = min(max(0.75 * semi_x, 0.1), 0.5)
    pole_long_y = min(max(0.75 * semi_y, 0.1), 0.5)

    poles = []
    hw, hh = pole_thick_x, pole_long_y
    for sign in (+1, -1):
        xc = sign * (semi_x + hw)
        poles.append(pv.Box(bounds=[xc - hw, xc + hw, -hh, hh, 0.0, length]))
    hw, hh = pole_long_x, pole_thick_y
    for sign in (+1, -1):
        yc = sign * (semi_y + hh)
        poles.append(pv.Box(bounds=[-hw, hw, yc - hh, yc + hh, 0.0, length]))
    mesh = poles[0]
    for pole in poles[1:]:
        mesh = mesh + pole
    return mesh


def build_cells(length, semi_x, semi_y, profile):
    """Build a cell-like cavity by varying the tube radius along z."""
    mesh = None
    segment = length / len(profile)
    for i, scale in enumerate(profile):
        part = cylinder(segment, semi_x, semi_y, z0=i * segment, scale=scale)
        mesh = part if mesh is None else mesh + part
    return mesh


# -----------------------------------------------------------------------------
# Element sources
# -----------------------------------------------------------------------------

class OpalXElementSource(ABC):
    """Base class for an element geometry source.

    Subclasses consume an element description (from the JSON file) and an
    argparse namespace, and produce a ``pv.PolyData`` mesh in element-local
    coordinates. The caller is responsible for transforming to global
    coordinates and attaching category cell data.
    """

    def __init__(self, element, args, reference):
        self.element = element
        self.args = args
        self.reference = reference

    @abstractmethod
    def execute(self):
        """Return the local-coordinate mesh for this element, or None."""

    def _effective_transverse(self):
        return effective_transverse(self.element, self.args, self.reference)

    def _add_metadata(self, mesh, clamped):
        mesh.field_data['element'] = [self.element['name']]
        mesh.field_data['etype'] = [self.element['type']]
        mesh.field_data['clamped'] = [np.uint8(clamped)]
        return mesh

    def build(self):
        """Convenience wrapper that returns the mesh with metadata attached."""
        return self.execute()


class OpalXBendSource(OpalXElementSource):
    """Bend vacuum chamber swept along the design path."""

    def execute(self):
        (semi_x, semi_y), clamped = self._effective_transverse()
        if self.args.simple_geometry:
            return self._build_tube(semi_x, semi_y, clamped)
        return self._build_swept(semi_x, semi_y, clamped)

    def _build_tube(self, semi_x, semi_y, clamped):
        points = np.asarray(self.element.get('design_path', []), dtype=float)
        if len(points) < 2:
            return None
        # Circular tube whose area approximates the aperture area
        radius = math.hypot(semi_x, semi_y) / math.sqrt(2.0)
        points = (
            pose_matrix(self.element)
            @ np.hstack([points, np.ones((len(points), 1))]).T
        ).T[:, :3]
        mesh = pv.lines_from_points(points).tube(radius=radius, n_sides=24)
        return self._add_metadata(mesh, clamped)

    def _build_swept(self, semi_x, semi_y, clamped):
        points = np.asarray(self.element.get('design_path', []), dtype=float)
        if len(points) < 2:
            return self._build_tube(semi_x, semi_y, clamped)
        kind = self.element.get('transverse', {}).get('kind', 'elliptical')
        if kind == 'rectangular':
            loop = rectangular_loop(semi_x, semi_y)
        else:
            loop = elliptical_loop(semi_x, semi_y)
        mesh = sweep_profile(points, [loop], caps=self.args.capped)
        if mesh is None:
            return self._build_tube(semi_x, semi_y, clamped)
        mesh = place(mesh, self.element)
        return self._add_metadata(mesh, clamped)


class OpalXSolenoidSource(OpalXElementSource):
    """Solenoid support envelope: hollow tube by default, solid with --simple-geometry."""

    def execute(self):
        (semi_x, semi_y), clamped = self._effective_transverse()
        length = self.element.get('length', 0.0)
        if length <= 0.0:
            return None
        if self.args.simple_geometry:
            mesh = self._build_solid(length, semi_x, semi_y)
        else:
            mesh = self._build_hollow(length, semi_x, semi_y)
        if mesh is None:
            return None
        mesh = place(mesh, self.element)
        return self._add_metadata(mesh, clamped)

    def _build_solid(self, length, semi_x, semi_y):
        body = cylinder(length, semi_x, semi_y, capped=self.args.capped)
        collar_length = min(0.18 * length, 0.8 * min(semi_x, semi_y))
        if collar_length <= 1e-12 or 2.0 * collar_length >= length:
            return body
        mesh = body
        for z0 in (0.0, length - collar_length):
            mesh = mesh + cylinder(
                collar_length, semi_x * 1.18, semi_y * 1.18,
                capped=self.args.capped, z0=z0
            )
        return mesh

    def _build_hollow(self, length, semi_x, semi_y, inner_scale=0.45):
        body = hollow_tube(
            length, semi_x, semi_y, inner_scale=inner_scale
        )
        collar_length = min(0.18 * length, 0.8 * min(semi_x, semi_y))
        if collar_length <= 1e-12 or 2.0 * collar_length >= length:
            return body
        mesh = body
        for z0 in (0.0, length - collar_length):
            mesh = mesh + hollow_tube(
                collar_length, semi_x * 1.18, semi_y * 1.18,
                inner_scale=inner_scale, z0=z0
            )
        return mesh


class OpalXMultipoleSource(OpalXElementSource):
    """MULTIPOLE / MULTIPOLET element. Order 2 is drawn as four poles."""

    def execute(self):
        (semi_x, semi_y), clamped = self._effective_transverse()
        length = self.element.get('length', 0.0)
        if length <= 0.0:
            return None
        if self.element.get('multipole_order') == 2:
            mesh = build_quadrupole(length, semi_x, semi_y)
        else:
            mesh = cylinder(length, semi_x, semi_y, capped=self.args.capped)
        mesh = place(mesh, self.element)
        return self._add_metadata(mesh, clamped)


class OpalXDriftSource(OpalXElementSource):
    """Drift / collimator / stop: cylinder or rectangular box from aperture."""

    def execute(self):
        (semi_x, semi_y), clamped = self._effective_transverse()
        length = self.element.get('length', 0.0)
        if length <= 0.0:
            return None
        if self.element.get('transverse', {}).get('kind') == 'rectangular':
            mesh = box(length, semi_x, semi_y)
        else:
            mesh = cylinder(length, semi_x, semi_y, capped=self.args.capped)
        mesh = place(mesh, self.element)
        return self._add_metadata(mesh, clamped)


class OpalXCavitySource(OpalXElementSource):
    """RF / travelling-wave / constant-E-field cavity."""

    def execute(self):
        (semi_x, semi_y), clamped = self._effective_transverse()
        length = self.element.get('length', 0.0)
        if length <= 0.0:
            return None
        etype = self.element['type']
        if etype == 'RFCAVITY':
            profile = [0.78, 1.15, 0.82, 1.25, 0.82, 1.15, 0.78]
        elif etype == 'TRAVELINGWAVE':
            profile = [0.92, 1.05] * 4
        else:
            profile = [1.0]
        mesh = build_cells(length, semi_x, semi_y, profile)
        mesh = place(mesh, self.element)
        return self._add_metadata(mesh, clamped)


class OpalXMonitorSource(OpalXElementSource):
    """Monitor / marker / probe: thin annular disc for visual confirmation."""

    def execute(self):
        (semi_x, semi_y), clamped = self._effective_transverse()
        if semi_x <= 0.0 or semi_y <= 0.0:
            return None
        length = self.element.get('length', 0.0)
        if length <= 0.0:
            length = 0.01
        # Use VTK's disk source for a robust annular disc, then extrude it
        # slightly to make a thin washer. The hole radius is 90% of the
        # aperture so the beam pipe remains visible.
        disc = pv.Disc(
            inner=0.9 * semi_x, outer=semi_x,
            r_res=1, c_res=32, normal=(0.0, 0.0, 1.0)
        )
        if semi_y != semi_x:
            disc.scale([1.0, semi_y / semi_x, 1.0], inplace=True)
        mesh = disc.extrude((0.0, 0.0, length), capping=True)
        mesh = place(mesh, self.element)
        return self._add_metadata(mesh, clamped)


class OpalXGenericSource(OpalXElementSource):
    """Fallback source for any unhandled element type."""

    def execute(self):
        (semi_x, semi_y), clamped = self._effective_transverse()
        length = self.element.get('length', 0.0)
        if length <= 0.0:
            return None
        mesh = cylinder(length, semi_x, semi_y, capped=self.args.capped)
        mesh = place(mesh, self.element)
        return self._add_metadata(mesh, clamped)


